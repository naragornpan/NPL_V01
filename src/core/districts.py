# เรียงจากยาวไปสั้น เพื่อให้จับ "เมืองนนทบุรี" ก่อน "นนทบุรี"
ALL_DISTRICTS: list[tuple[str, str]] = sorted(
    ((d, p) for p, ds in DISTRICTS.items() for d in ds),
    key=lambda x: -len(x[0]),
)


def match_district(text: str | None, province: str | None = None) -> str | None:
    """หาอำเภอ/เขตจากข้อความที่คำติดกัน

    ถ้าระบุจังหวัดมาด้วย จะค้นเฉพาะอำเภอในจังหวัดนั้น (แม่นกว่าและเร็วกว่า)
    คืน None ถ้าไม่เจอ — ดีกว่าเดาผิด เพราะข้อมูลผิดแย่กว่าข้อมูลว่าง
    """
    if not text:
        return None
    candidates = (
        [(d, province) for d in DISTRICTS.get(province, [])]
        if province and province in DISTRICTS
        else ALL_DISTRICTS
    )
    for district, _ in sorted(candidates, key=lambda x: -len(x[0])):
        if district in text:
            return district
    return None


def province_of(district: str) -> str | None:
    for d, p in ALL_DISTRICTS:
        if d == district:
            return p
    return None


def is_tier1(province: str | None) -> bool:
    return province in DISTRICTS
