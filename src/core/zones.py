"""Zone configuration — ลำดับการขยายพื้นที่

หลักการ: ingestion กว้าง / focus แคบ

  ingestion  = เก็บข้อมูลไว้ก่อน ถูกมาก และย้อนเก็บไม่ได้
               (รายงานผลการขายของ LED ย้อนหลังได้แค่ 6 เดือน)
  focus_zone = พื้นที่ที่ลงไปสำรวจจริง หาผู้รับเหมา สร้างบ่อผู้ซื้อ
               ต้องแคบ เพราะข้อได้เปรียบมาจากความลึก ไม่ใช่ความกว้าง

อย่าเพิ่ง hardcode focus_zone — ปล่อยให้ข้อมูล 4 สัปดาห์แรกเป็นคนเลือก
ดู queries/pick_focus_zone.sql
"""
from __future__ import annotations

# ---------------------------------------------------------------------
# Tier 1 — กรุงเทพ + ปริมณฑล  (เริ่มที่นี่)
# ---------------------------------------------------------------------
TIER_1_BKK_METRO = [
    "กรุงเทพมหานคร",
    "นนทบุรี",
    "ปทุมธานี",
    "สมุทรปราการ",
    "สมุทรสาคร",
    "นครปฐม",
]

# ---------------------------------------------------------------------
# Tier 2 — พื้นที่เศรษฐกิจ EEC + ปริมณฑลรอบนอก
# เปิดเมื่อ tier 1 รันนิ่งแล้วอย่างน้อย 2 สัปดาห์
# ---------------------------------------------------------------------
TIER_2_ECONOMIC = [
    "ชลบุรี",
    "ระยอง",
    "ฉะเชิงเทรา",
    "พระนครศรีอยุธยา",
]

# ---------------------------------------------------------------------
# Tier 3 — หัวเมืองหลักรายภาค
# เปิดเมื่อมี buyer requirement จากพื้นที่นั้นจริง อย่าเปิดล่วงหน้า
# ---------------------------------------------------------------------
TIER_3_REGIONAL = [
    "เชียงใหม่",        # เหนือ
    "นครราชสีมา",       # อีสานใต้
    "ขอนแก่น",          # อีสานกลาง
    "อุดรธานี",         # อีสานเหนือ
    "สุราษฎร์ธานี",     # ใต้ตอนบน
    "ภูเก็ต",           # อันดามัน
    "สงขลา",            # ใต้ตอนล่าง
]

TIERS = {
    1: TIER_1_BKK_METRO,
    2: TIER_1_BKK_METRO + TIER_2_ECONOMIC,
    3: TIER_1_BKK_METRO + TIER_2_ECONOMIC + TIER_3_REGIONAL,
}


def provinces_for_tier(tier: int) -> list[str]:
    if tier not in TIERS:
        raise ValueError(f"tier ต้องเป็น {sorted(TIERS)} ได้รับ {tier}")
    return TIERS[tier]


def estimated_runtime_minutes(tier: int, max_pages: int, rate_limit_s: float) -> float:
    """ประเมินเวลารันก่อนตั้ง cron — GitHub Actions ตั้ง timeout ไว้ 30 นาที

    tier 3 กับ max_pages สูง ๆ จะทะลุ timeout ได้ ถ้าเกิน 25 นาที
    ให้แตก workflow เป็นหลาย job ตาม tier แทนการเพิ่ม timeout
    """
    return len(provinces_for_tier(tier)) * max_pages * rate_limit_s / 60


